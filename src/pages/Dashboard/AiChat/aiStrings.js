export function makeTr(lang, overrides) {
  const map = AI_STRINGS[lang] || AI_STRINGS.EN;
  const ov = overrides ? (overrides[lang] || {}) : {};
  const ovEn = overrides ? overrides.EN : {};
  return (key, vars) => {
    let s = ov[key] != null ? ov[key] : (map[key] != null ? map[key] : (ovEn[key] != null ? ovEn[key] : (AI_STRINGS.EN[key] != null ? AI_STRINGS.EN[key] : key)));
    if (vars) Object.keys(vars).forEach((k) => { s = s.split('{' + k + '}').join(vars[k]); });
    return s;
  };
}
